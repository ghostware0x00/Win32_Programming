//#undef UNICODE  // forces CreateFile() to accept char* ANSI strings. This needs to be included at the top of the file
#include <Windows.h>
#include <iostream>
#define BUFF_SIZE 256


int main(int argc, LPTSTR argv[]){ 
    /*
        LPTSTR stands for Long Pointer TCHAR string
        TCHAR becomes wchar_t(UNICODE defined) and char(ANSI/UNICODE undefined).
        char* argv causes compile time error cause CreateFile() needs wchar_t* but we gave char*
        but if we supply wchar_t* argv[] that violates the main() signature so we use LPTSTR because 

        If Unicode is defined(Default in Modern Windows)
        LPTSTR becomes wchar_t* everywhere
        CreateFile becomes CreateFileW => both accept wide characters

        If UNICODE is undefined(Legacy/ANSII)
        LPTSTR becomes char* everywhere
        CreateFile becomes CreateFileA => both accept narrow characters or (char) type data


        In our code since UNICODE is undefined when we pass LPTSTR 
        main() gets char* argv
        and CreateFile() becomes CreateFileA() so it accepts narrow characters or (char) type data without any compile time errors
    */
    CHAR buffer[BUFF_SIZE];
    // performing file copy 
    // there are 2 ways to do this
    /*
        1. create file and then read it and then write the contents (manually)
        2. copyfile win32api function
    */
   // we will learn to do it in 2 ways
   // CreateFile(), ReadFile(), WriteFile()
    if(argc != 3){
        std::cout << "[!] usage : cp1 file1 file2" << std::endl;
        return -1;
    }
   /*
   CreateFile() creates a new file or opens an existing file if exists
   arguments required by CreateFile() :-
   <-------------------------------------------->
        HANDLE CreateFile(
        LPCSTR                lpFileName,
        DWORD                 dwDesiredAccess,
        DWORD                 dwShareMode,
        LPSECURITY_ATTRIBUTES lpSecurityAttributes,
        DWORD                 dwCreationDisposition,
        DWORD                 dwFlagsAndAttributes,
        HANDLE                hTemplateFile
        );

    • lpFileName: The file path string (e.g., argv[1]).
    • dwDesiredAccess: The access mode. GENERIC_READ to read, GENERIC_WRITE to write, or a combination (GENERIC_READ | GENERIC_WRITE).
    • dwShareMode: Sharing rules for other programs. FILE_SHARE_READ lets others read it; 0 locks the file completely.
    • lpSecurityAttributes: Pointer to security structures. Passing NULL gives default security and prevents child processes from inheriting the file handle.
    • dwCreationDisposition: Action to take based on whether the file exists.
        • OPEN_EXISTING: Open if it exists; fail if it doesn't.
        • CREATE_ALWAYS: Overwrite/create a fresh file regardless of whether it exists.
    • dwFlagsAndAttributes: File settings. FILE_ATTRIBUTE_NORMAL is standard.
    • hTemplateFile: A handle to a template file containing attributes to copy. Almost always passed as NULL.

   
        HANDLE vs HWND
        HANDLE : a generic token that references any system managed resource in the Windows
        HWND : a specific type of handle which is exclusively used to identify UI window objects.
   */
    HANDLE h1, h2; 
    DWORD bytesRead, bytesReceived;
    // since 
    h1 = CreateFile(argv[1], GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, NULL);
    if(h1 == INVALID_HANDLE_VALUE){
        // since argv is wide string literal we need to use wcout to print its contents instead of using std::cout
        std::wcout << "[!] Failed to open " << argv[1] << std::endl;
        std::cout << GetLastError() << std::endl;
        return -2;
    }
    h2 = CreateFile(argv[2], GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    if(h2 == INVALID_HANDLE_VALUE){
        std::wcout << "[!] Failed to create " << argv[2] << std::endl;
        std::cout << GetLastError() << std::endl;
        return -3;
    }
    /*
    ReadFile() is used to read from an open file handle into local memory buffer
    arguments requried by ReadFile() :-
    <----------------------------------------->

        BOOL ReadFile(
            HANDLE       hFile,
            LPVOID       lpBuffer,
            DWORD        nNumberOfBytesToRead,
            LPDWORD      lpNumberOfBytesRead,
            LPOVERLAPPED lpOverlapped
        );

        • hFile: The active source file handle generated by CreateFile (e.g., hIn).
        • lpBuffer: The memory pointer or array where data will be stored (e.g., buffer).
        • nNumberOfBytesToRead: The maximum chunk size to fetch per pass (e.g., BUF_SIZE, which is 256).
        • lpNumberOfBytesRead: A pointer to a variable that receives the actual count of bytes read (e.g., &nIn). Crucial because the last read pass is often smaller than the maximum buffer size.
        • lpOverlapped: Pointer to an asynchronous tracking structure. Set to NULL for synchronous (blocking) file reading.

    */
    // ReadFile() is in while loop because data is read in a stream so the total bytes we want to read might not be read in a single ReadFile() function so we need to read until it has reached End of File(EOF)
    while(ReadFile(h1, buffer, BUFF_SIZE, &bytesRead, NULL) && bytesRead > 0){ 
        /*
            WriteFile() is used to push data from the local memory buffer into the open file handle
            arguments required by WriteFile()
            <---------------------------------->

            BOOL WriteFile(
                HANDLE       hFile,
                LPCVOID      lpBuffer,
                DWORD        nNumberOfBytesToWrite,
                LPDWORD      lpNumberOfBytesWritten,
                LPOVERLAPPED lpOverlapped
            );
            
            • hFile: The active destination file handle generated by CreateFile (e.g., hOut).
            • lpBuffer: The local memory pointer holding the data you want to export (e.g., buffer).
            • nNumberOfBytesToWrite: The exact number of bytes to commit to disk. Notice your code passes nIn here, making sure it only writes exactly what was successfully read.
            • lpNumberOfBytesWritten: A pointer to a variable that receives the count of bytes successfully written to the disk (e.g., &nOut).
            • lpOverlapped: Set to NULL for standard, synchronous file writing.
        */
        WriteFile(h2, buffer, bytesRead, &bytesReceived, NULL);
        if(bytesRead != bytesReceived){
            std::cout << "[!] Fatal write : " << GetLastError() << std::endl;
            return -4;
        }
    }
    // handles must be closed because they use system resources and consume kernel memory.
    /*
        kernel memory is a dedicated, privileged RAM used by operating system to manage hardware, drivers, system operations.
    */
    CloseHandle(h1);
    CloseHandle(h2);
    return 0;
}